JEV_OTHER_KEY = 'other'
JEV_OTHER_DESC = '以上都不是（这道题不属于给出的任何知识点）'
JEV_MAX_OPTIONS = 255  # Jev 单个 Choice 的选项上限

# Jev 是「System 1」直觉模型，不做推理链 ⇒ **criteria 的描述质量几乎决定命中率**，
# 这和 chat 引擎完全不同（chat 能读长 prompt 自己推理）。
#
# ⚠️⚠️ **优先用知识点表自己的 description 字段**（见 `build_jev_criteria`）——
# 那才是页面上能维护的地方。这张表只是「description 为空时的兜底」。
#
# 两条硬性写法约束（2026-09-25 实测，违反了会让准确率下降）：
#   1. 每条只说一件事 —— 塞进 6 个互不相干概念的那条（旧「和差倍比问题」）实测把类变成了
#      垃圾桶，去掉全部描述反而更好（平均置信度 0.845 → 0.872）；
#   2. 类与类之间不许重叠 —— 一重叠模型就摇摆，confidence 直接掉到 0.5。
